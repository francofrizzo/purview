import { useMemo, useState } from "react";
import type { Concept, Example, Flow, PrDetail, RemoteConversationComment, RemoteReview, ReviewUnit } from "../api/types";
import { unitProgress } from "../lib/diffModel";
import { workUnits } from "../lib/generated";
import { buildTimeline, latestVerdicts, type RevisionContext } from "../lib/reviews";
import type { ThreadFilters } from "../lib/threads";
import { unitDisplayNumbers, unitDisplayOrder } from "../lib/unitOrder";
import { FlowLegend, FlowView } from "./Shape";
import { AuthorAvatar } from "./AuthorAvatar";
import { InlineMarkdown, Markdown } from "./Markdown";
import { ReviewTimeline, ReviewerVerdicts } from "./Reviews";
import { withoutHeadings } from "./SummaryStrip";
import { IconArrowRight, IconChevron } from "./icons";

/**
 * The PR before its parts, from broad to narrow: why it exists (the
 * analysis's summary, in plain words), the words the PR leans on, one case
 * before and after, then what to read closely; the author's description, in
 * their own words and whole, and what reviewers said close it. One calm column; everything here is a way into the
 * guide. Where each file lands is in the Files view, beside each file.
 */
export function Overview({
  detail,
  summary,
  description,
  reviews,
  conversation,
  filters,
  revisions,
  onOpenUnit,
}: {
  detail: PrDetail;
  summary: string;
  description: string;
  reviews?: RemoteReview[];
  conversation?: RemoteConversationComment[];
  filters?: ThreadFilters;
  revisions?: RevisionContext;
  onOpenUnit: (unitId: string) => void;
}) {
  const { meta, state } = detail;
  const ordered = useMemo(() => unitDisplayOrder(state.units), [state.units]);
  const numbers = useMemo(() => unitDisplayNumbers(ordered), [ordered]);
  const work = workUnits(ordered);
  const timeline = useMemo(() => buildTimeline(reviews, conversation, filters), [reviews, conversation, filters]);
  const verdicts = useMemo(
    () => latestVerdicts(reviews, { prAuthor: meta.author, filters, revisions }),
    [reviews, meta.author, filters, revisions],
  );
  const hasReviews = timeline.entries.length > 0 || timeline.hidden > 0;
  const next =
    ordered.find((u) => {
      const p = unitProgress(detail, u);
      return p.total > 0 && p.viewed < p.total;
    }) ?? ordered[0];
  const started = ordered.some((u) => unitProgress(detail, u).viewed > 0);
  const close = ordered.filter((u) => u.attention === "must-read");
  const rest = restLine(
    close.length,
    ordered.filter((u) => u.attention === "skim").length,
    ordered.filter((u) => u.attention === "skip").length,
  );

  return (
    <div className="h-full overflow-y-auto" data-testid="overview">
      {/* Text keeps a reading measure; the flow gets the room it needs. */}
      <div className="flex flex-col gap-10 px-6 pb-16 pt-8 sm:px-10 [&>section]:mx-auto [&>section]:w-full [&>section]:max-w-[54rem] [&>section.wide]:max-w-[88rem]">
        {summary ? (
          <section data-testid="pr-summary">
            <p className="mb-2 text-2xs" style={{ color: "var(--fg-faint)" }} data-testid="pr-summary-byline">
              Generated by Purview
            </p>
            <div className="[&>div]:text-[15px] [&>div]:leading-[25px]" style={{ color: "var(--fg)" }}>
              <Markdown text={withoutHeadings(summary.trim())} />
            </div>
          </section>
        ) : null}

        {state.concepts?.length ? <ConceptList concepts={state.concepts} /> : null}

        {/* One case through the change; the call sequence, when drawn, is the
            same story told in the code, so it folds under it. Without an
            example (analyses from before it) the flow stands on its own. */}
        {state.example ? (
          <ExampleView example={state.example} flow={state.flow} units={work} onOpenUnit={onOpenUnit} />
        ) : state.flow ? (
          <section data-testid="overview-flow" className="wide">
            <div className="mx-auto max-w-[54rem]">
              <SectionHead title="How it runs">
                <FlowLegend flow={state.flow} />
              </SectionHead>
              {state.flow.caption ? (
                <p className="mb-3 text-[13px] leading-[21px]" style={{ color: "var(--fg-muted)" }}>
                  <InlineMarkdown text={state.flow.caption} />
                </p>
              ) : null}
            </div>
            <div className="pane rounded-lg px-3 py-4" style={{ background: "var(--bg-raised)" }}>
              <FlowView flow={state.flow} units={work} onOpenUnit={onOpenUnit} />
            </div>
          </section>
        ) : null}

        {/* Where to spend attention: only what needs a close read, each with
            the analysis's why. The rest is counted; the guide lists it all. */}
        {ordered.length ? (
          <section data-testid="reading-order">
            <SectionHead title="Read closely">
              {next ? (
                <button
                  type="button"
                  className="btn"
                  data-testid="start-reading"
                  onClick={() => onOpenUnit(next.id)}
                >
                  {started ? "Continue" : "Start reading"}
                  <IconArrowRight width={12} height={12} />
                </button>
              ) : null}
            </SectionHead>
            {close.length ? (
              <ol className="flex flex-col">
                {close.map((u) => (
                  <li key={u.id}>
                    <ReadingRow
                      unit={u}
                      number={numbers.get(u.id) ?? u.order}
                      progress={unitProgress(detail, u)}
                      onOpen={() => onOpenUnit(u.id)}
                    />
                  </li>
                ))}
              </ol>
            ) : null}
            {rest ? (
              // Under the titles' column when it follows rows, flush when alone.
              <p className={`text-xs ${close.length ? "mt-2 pl-8" : ""}`} style={{ color: "var(--fg-muted)" }} data-testid="reading-rest">
                {rest}
              </p>
            ) : null}
          </section>
        ) : null}

        {description ? (
          <section data-testid="pr-description">
            <SectionHead
              title={
                <span className="flex items-center gap-1.5">
                  {meta.author ? <AuthorAvatar author={meta.author} url={meta.authorAvatarUrl} size={14} /> : null}
                  Description
                  {meta.author ? (
                    <span className="font-normal" style={{ color: "var(--fg-faint)" }}>
                      by {meta.author}
                    </span>
                  ) : null}
                </span>
              }
            />
            <div className="[&>div]:text-[13px] [&>div]:leading-[21px]">
              <Markdown text={description} />
            </div>
          </section>
        ) : null}

        {hasReviews ? (
          <section data-testid="pr-reviews">
            <SectionHead title="Reviews">
              <ReviewerVerdicts verdicts={verdicts} />
            </SectionHead>
            <ReviewTimeline entries={timeline.entries} hidden={timeline.hidden} revisions={revisions} />
          </section>
        ) : null}
      </div>
    </div>
  );
}

/**
 * The words the PR leans on, each with its meaning; the same meanings show on
 * hover wherever the guide uses them. The code's own names for a concept sit
 * faint beside it, so the reader can recognize them in the units.
 */
function ConceptList({ concepts }: { concepts: Concept[] }) {
  return (
    <section data-testid="overview-concepts">
      <SectionHead title="Concepts" />
      <dl className="grid gap-x-6 gap-y-3 sm:grid-cols-[minmax(8rem,auto)_1fr]">
        {concepts.map((c) => (
          <div key={c.term} className="contents" data-testid="concept">
            <dt className="flex flex-wrap items-baseline gap-x-1.5 text-[13px] font-medium leading-5" style={{ color: "var(--fg)" }}>
              {c.term}
              {c.isNew ? (
                <span className="chip" style={{ color: "var(--accent)", background: "var(--accent-soft)" }} data-testid="concept-new">
                  new
                </span>
              ) : null}
            </dt>
            <dd className="-mt-2 text-[13px] leading-5 sm:mt-0" style={{ color: "var(--fg-muted)" }}>
              {c.means}
              {/* The first names are enough to recognize it in the units;
                  the rest only feed the hover. */}
              {c.aka.length ? (
                <span className="ml-1.5 font-mono text-2xs" style={{ color: "var(--fg-faint)" }} data-tip="As the code and the guide call it">
                  {c.aka.slice(0, 2).join(" · ")}
                </span>
              ) : null}
            </dd>
          </div>
        ))}
      </dl>
    </section>
  );
}

/**
 * One case before and after the change, side by side so the difference is
 * what stands out. The flow, when the analysis drew one, is the same change
 * in the code: one click away, not in the way.
 */
function ExampleView({
  example,
  flow,
  units,
  onOpenUnit,
}: {
  example: Example;
  flow?: Flow;
  units: ReviewUnit[];
  onOpenUnit: (unitId: string) => void;
}) {
  const [calls, setCalls] = useState(false);
  const column = (label: string, steps: string[], now: boolean) => (
    <div
      className="rounded-lg px-4 py-3"
      style={{
        background: now ? "var(--bg-raised)" : "transparent",
        border: `1px solid ${now ? "var(--border-strong)" : "var(--border)"}`,
      }}
      data-testid={now ? "example-after" : "example-before"}
    >
      <p className="mb-2 text-2xs font-medium uppercase tracking-wider" style={{ color: "var(--fg-faint)" }}>
        {label}
      </p>
      <ol className="flex list-decimal flex-col gap-1.5 pl-4 text-[13px] leading-5" style={{ color: now ? "var(--fg)" : "var(--fg-muted)" }}>
        {steps.map((step, i) => (
          <li key={i}>{step}</li>
        ))}
      </ol>
    </div>
  );
  return (
    <section data-testid="overview-example" className={calls ? "wide" : undefined}>
      <div className="mx-auto max-w-[54rem]">
        <SectionHead title="An example" />
        <p className="mb-3 text-[13px] font-medium leading-5" style={{ color: "var(--fg)" }} data-testid="example-case">
          {example.case}
        </p>
        <div className="grid gap-3 sm:grid-cols-2">
          {column("Before", example.before, false)}
          {column("Now", example.after, true)}
        </div>
        {flow ? (
          <button
            type="button"
            className="mt-3 flex items-center gap-1 text-xs transition-colors hover:text-[var(--fg)]"
            style={{ color: "var(--fg-faint)" }}
            aria-expanded={calls}
            data-testid="example-calls-toggle"
            onClick={() => setCalls((v) => !v)}
          >
            <IconChevron open={calls} width={10} height={10} />
            The calls, in the code
          </button>
        ) : null}
      </div>
      {flow && calls ? (
        <div className="mt-3" data-testid="overview-flow">
          <div className="mx-auto mb-2 flex max-w-[54rem] items-baseline gap-3">
            {flow.caption ? (
              <p className="text-xs leading-[19px]" style={{ color: "var(--fg-muted)" }}>
                <InlineMarkdown text={flow.caption} />
              </p>
            ) : null}
            <span className="ml-auto flex-none">
              <FlowLegend flow={flow} />
            </span>
          </div>
          <div className="pane rounded-lg px-3 py-4" style={{ background: "var(--bg-raised)" }}>
            <FlowView flow={flow} units={units} onOpenUnit={onOpenUnit} />
          </div>
        </div>
      ) : null}
    </section>
  );
}

/** What is left after the close reads, as one line of counts. */
function restLine(close: number, skim: number, skip: number): string {
  const parts = [skim ? `${skim} to skim` : "", skip ? `${skip} to skip` : ""].filter(Boolean);
  if (!parts.length) return "";
  return close ? `Then ${parts.join(" and ")}.` : `Nothing needs a close read: ${parts.join(", ")}.`;
}

function SectionHead({ title, children }: { title: React.ReactNode; children?: React.ReactNode }) {
  return (
    <div className="mb-3 flex flex-wrap items-center gap-x-4 gap-y-1">
      <h2 className="text-[13px] font-semibold" style={{ color: "var(--fg)" }}>
        {title}
      </h2>
      {children ? <div className="ml-auto flex items-center gap-2">{children}</div> : null}
    </div>
  );
}

function ReadingRow({
  unit,
  number,
  progress,
  onOpen,
}: {
  unit: ReviewUnit;
  number: number;
  progress: { viewed: number; total: number };
  onOpen: () => void;
}) {
  const done = progress.total > 0 && progress.viewed === progress.total;
  return (
    <button
      type="button"
      onClick={onOpen}
      data-testid={`reading-row-${unit.id}`}
      className="group -mx-2 flex w-[calc(100%+1rem)] items-baseline gap-3 rounded-md px-2 py-2 text-left transition-colors hover:bg-[var(--bg-hover)]"
    >
      <span className="w-5 flex-none text-right text-xs tabular-nums" style={{ color: "var(--fg-faint)" }}>
        {number}
      </span>
      <span className="min-w-0 flex-1">
        <span
          className="block text-[13px] font-medium leading-5"
          style={{ color: done ? "var(--fg-muted)" : "var(--fg)" }}
        >
          <InlineMarkdown text={unit.title} />
        </span>
        {unit.attentionWhy ? (
          <span className="mt-0.5 block text-xs leading-[18px]" style={{ color: "var(--fg-faint)" }}>
            <InlineMarkdown text={unit.attentionWhy} />
          </span>
        ) : null}
      </span>
      <span
        className="flex-none text-2xs tabular-nums"
        style={{ color: done ? "var(--ok)" : "var(--fg-faint)" }}
      >
        {progress.total ? `${progress.viewed}/${progress.total}` : ""}
      </span>
    </button>
  );
}
