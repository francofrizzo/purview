import { describe, expect, it } from "vitest";
import type { FileEntry } from "../api/types";
import { changeMix, formatShare } from "./changeMix";

const file = (path: string, added: number, removed: number, extra: Partial<FileEntry> = {}): FileEntry =>
  ({
    path,
    hunks: [{ id: path, addedLines: Array(added).fill("x = 1"), removedLines: Array(removed).fill("x = 0") }],
    ...extra,
  }) as FileEntry;

const counts = (files: FileEntry[], only?: Set<string>) =>
  Object.fromEntries(changeMix(files, only).rows.map((r) => [r.kind, [r.added, r.removed]]));

describe("changeMix", () => {
  it("sorts lines by what their file is, and keeps migrations with the implementation", () => {
    expect(
      counts([
        file("src/charge.ts", 10, 2),
        file("migrations/0042.sql", 5, 0),
        file("src/charge.test.ts", 20, 1),
        file("src/__snapshots__/charge.snap", 4, 0),
        file("docs/billing.md", 3, 3),
        file("pnpm-lock.yaml", 100, 50, { generated: { source: "lockfile" } } as Partial<FileEntry>),
      ]),
    ).toEqual({ implementation: [15, 2], tests: [24, 1], docs: [3, 3], generated: [100, 50] });
  });

  it("calls a hunk with a generated marker generated, whatever its file", () => {
    const mix = changeMix([file("src/client.ts", 0, 0), { ...file("src/client.ts", 0, 0), hunks: [{ id: "a", addedLines: ["// Code generated by protoc"] }] } as FileEntry]);
    expect(mix.rows.map((r) => r.kind)).toEqual(["generated"]);
  });

  it("counts lines no hunk holds by what the file is", () => {
    const tooBig = { ...file("src/big.test.ts", 0, 0), hunks: [], additions: 900, deletions: 12 } as FileEntry;
    expect(counts([tooBig])).toEqual({ tests: [900, 12] });
  });

  it("reads only the unit's hunks when given them, and gives each kind its share of the lines", () => {
    const files = [file("src/a.ts", 15, 5), file("src/a.test.ts", 60, 20), file("src/other.ts", 500, 0)];
    const mix = changeMix(files, new Set(["src/a.ts", "src/a.test.ts"]));
    expect(mix.rows.map((r) => [r.kind, r.percent])).toEqual([
      ["implementation", 20],
      ["tests", 80],
    ]);
    expect([mix.added, mix.removed]).toEqual([75, 25]);
  });

  it("is empty for a change with no lines", () => {
    expect(changeMix([]).rows).toEqual([]);
  });
});

describe("formatShare", () => {
  it("rounds, and never calls lines 0%", () => {
    expect(formatShare(79.6)).toBe("80%");
    expect(formatShare(0.4)).toBe("<1%");
  });
});
