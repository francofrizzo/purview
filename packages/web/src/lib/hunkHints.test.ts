import { describe, expect, it } from "vitest";
import type { FileEntry, Hunk } from "../api/types";
import { hunkHint } from "./hunkHints";

const hunk = (added: string[], removed: string[] = []): Hunk => ({
  id: "h",
  file: "f",
  oldStart: 1,
  oldLines: 1,
  newStart: 1,
  newLines: 1,
  header: "@@",
  addedLines: added,
  removedLines: removed,
});
const file = (path: string, over: Partial<FileEntry> = {}): FileEntry => ({ path, hunks: [], ...over });

describe("hunkHint", () => {
  it("names glue by path", () => {
    expect(hunkHint(file("src/a.test.ts"), hunk(["x"]))).toBe("tests");
    expect(hunkHint(file("docs/guide.md"), hunk(["x"]))).toBe("docs");
    expect(hunkHint(file("src/__snapshots__/a.snap"), hunk(["x"]))).toBe("snapshot");
    expect(hunkHint(file("db/migrations/0012_add.sql"), hunk(["x"]))).toBe("migration");
    expect(hunkHint(file("pnpm-lock.yaml", { generated: { source: "lockfile" } }), hunk(["x"]))).toBe("lockfile");
    expect(hunkHint(file("api/a.pb.go", { generated: { source: "path" } }), hunk(["x"]))).toBe("generated");
  });

  it("names generated code by its marker and import-only hunks by their lines", () => {
    expect(hunkHint(file("src/a.ts"), hunk(["// Code generated by protoc. DO NOT EDIT."]))).toBe("generated");
    expect(
      hunkHint(file("src/a.ts"), hunk(['import { a } from "./a";', ""], ['const b = require("b");'])),
    ).toBe("imports only");
    expect(hunkHint(file("lib/x.py"), hunk(["from os import path", "import sys"]))).toBe("imports only");
  });

  it("says nothing about a hunk with real changes", () => {
    expect(hunkHint(file("src/charge.ts"), hunk(['import x from "x";', "return x + 1;"]))).toBeNull();
    expect(hunkHint(file("src/charge.ts"), hunk([]))).toBeNull();
  });
});
