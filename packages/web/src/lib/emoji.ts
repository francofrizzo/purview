/** Dedupe by character: a few entries above exist only to answer extra names. */
const BY_CHAR = new Map<string, EmojiEntry>();
for (const entry of EMOJI) {
  const have = BY_CHAR.get(entry.char);
  if (have) BY_CHAR.set(entry.char, { ...have, keywords: [...have.keywords, entry.name, ...entry.keywords] });
  else BY_CHAR.set(entry.char, entry);
}
export const EMOJI_LIST: readonly EmojiEntry[] = [...BY_CHAR.values()];

/**
 * The entries matching a query, best first: a name that starts with the
 * words beats a name that contains them, which beats a keyword hit. Empty
 * query: the list in its own order (reactions first). Words are matched
 * independently, so "green heart" finds 💚.
 */
export function searchEmoji(query: string, limit = 64): EmojiEntry[] {
  const words = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  if (!words.length) return EMOJI_LIST.slice(0, limit);
  const scored: { entry: EmojiEntry; score: number }[] = [];
  for (const entry of EMOJI_LIST) {
    const name = entry.name.replace(/_/g, " ");
    let score = 0;
    for (const w of words) {
      if (name === w || entry.name === w) score += 100;
      else if (name.startsWith(w)) score += 50;
      else if (name.includes(w)) score += 30;
      else if (entry.keywords.some((k) => k === w)) score += 20;
      else if (entry.keywords.some((k) => k.startsWith(w) || k.includes(w))) score += 10;
      else {
        score = 0;
        break;
      }
    }
    if (score > 0) scored.push({ entry, score });
  }
  return scored
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((s) => s.entry);
}
