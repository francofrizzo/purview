/* ------------------------------------------------------- GitHub review threads */

/**
 * Who wrote a comment on GitHub. `bot` is GitHub's own verdict (a Bot actor,
 * or a `[bot]` login) OR a login the reader listed as an AI reviewer in
 * settings; `botName` is a display name for known reviewers ("CodeRabbit").
 */
export interface RemoteAuthor {
  login: string;
  bot: boolean;
  botName?: string;
  avatarUrl?: string;
}

/** One comment inside a GitHub review thread. */
export interface RemoteComment {
  /** GraphQL node id */
  id: string;
  databaseId: number;
  author: RemoteAuthor;
  body: string;
  createdAt: string;
  /** set when edited after creation */
  updatedAt?: string;
  /** link on github.com */
  url: string;
  /** PENDING = sits in someone's (only ever the viewer's) unsubmitted review */
  reviewState: "PENDING" | "SUBMITTED";
  /** the viewer wrote it */
  isMine: boolean;
  /**
   * The id of the Purview comment this mirrors (matched on githubCommentId),
   * when there is one. The UI shows the local card instead of this copy, so a
   * comment pushed from Purview never appears twice.
   */
  localId?: string;
}

/**
 * A GitHub review thread: a root comment and its replies, anchored to a line
 * (or to a whole file). Several threads can sit on the same line.
 */
export interface RemoteThread {
  /** GraphQL node id — what reply/resolve take */
  id: string;
  path: string;
  subjectType: "line" | "file";
  /** current line on `side`; null when outdated or file-level */
  line: number | null;
  /** the line it was written on, at the commit it was written against */
  originalLine: number | null;
  /** first line of a multi-line comment, when it spans several */
  startLine: number | null;
  side: "LEFT" | "RIGHT";
  isResolved: boolean;
  /** the code it was written on changed since; `line` is then null */
  isOutdated: boolean;
  resolvedBy?: string;
  viewerCanResolve: boolean;
  viewerCanUnresolve: boolean;
  viewerCanReply: boolean;
  /** oldest first; [0] is the root */
  comments: RemoteComment[];
}

/**
 * A submitted review on the PR: its verdict and its top-level body (the
 * inline comments it carried live in `threads`). Pending reviews never appear.
 */
export interface RemoteReview {
  /** GraphQL node id */
  id: string;
  databaseId: number;
  author: RemoteAuthor;
  state: "APPROVED" | "CHANGES_REQUESTED" | "COMMENTED" | "DISMISSED";
  /** "" when the reviewer wrote nothing at the top level */
  body: string;
  submittedAt: string;
  /** link on github.com */
  url: string;
  /** inline comments submitted with this review */
  commentCount: number;
  /** the head commit it was written against (absent on older caches) */
  commitOid?: string;
  /** the viewer wrote it */
  isMine: boolean;
}

/** A comment on the PR's conversation tab (an issue comment, not on a line). */
export interface RemoteConversationComment {
  /** GraphQL node id */
  id: string;
  databaseId: number;
  author: RemoteAuthor;
  body: string;
  createdAt: string;
  /** set when edited after creation */
  updatedAt?: string;
  /** link on github.com */
  url: string;
  /** the viewer wrote it */
  isMine: boolean;
}

/**
 * GET /api/prs/:key/threads — the PR's review threads as GitHub has them,
 * plus its reviews and conversation comments (first 100 of each, oldest
 * first). Served from a per-PR cache when GitHub is unreachable: `error` is
 * then set and `fetchedAt` says how old the copy is (absent = never fetched).
 */
export interface ThreadsResponse {
  threads: RemoteThread[];
  reviews: RemoteReview[];
  conversation: RemoteConversationComment[];
  fetchedAt?: string;
  error?: string;
}

/** POST /api/prs/:key/threads/:id/resolve | /unresolve */
export interface ResolveThreadResult {
  thread: Pick<RemoteThread, "id" | "isResolved" | "resolvedBy" | "viewerCanResolve" | "viewerCanUnresolve">;
}
