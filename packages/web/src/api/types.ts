/**
 * Three states, mirroring the server:
 *   draft     — local only.
 *   pushed    — in your PENDING review on GitHub; private, still revocable.
 *   submitted — went out with a submitted review; public.
 */
export type CommentStatus = "draft" | "pushed" | "submitted";

/**
 * What a comment is attached to. `"line"` is the historical shape (and the
 * default when the server omits the field); `"file"` comments hang off the
 * whole file and carry no line or side at all.
 */
export type CommentSubject = "line" | "file";

export interface DraftComment {
  id: string;
  file: string;
  /** null for file-level comments */
  line: number | null;
  /** null for file-level comments */
  side: "LEFT" | "RIGHT" | null;
  body: string;
  createdAt?: string;
  status?: CommentStatus;
  /** absent on older servers — treat as "line" */
  subjectType?: CommentSubject;
  /** set once the comment exists on GitHub; needed to mirror an edit remotely */
  githubCommentId?: number;
  /** who created it; absent means the reader */
  author?: CommentActor;
  /** who made the latest body edit still in effect; absent = unedited (or undone) */
  lastEditedBy?: CommentActor;
  /** earlier bodies, oldest first — what "undo" goes back to */
  history?: { body: string; replacedAt: string; replacedBy: CommentActor }[];
  /** GraphQL node id of the GitHub thread this comment started, once pushed */
  githubThreadId?: string;
  /**
   * A reply to an existing GitHub review thread (GraphQL node id). Anchored
   * to the thread's file/line for display; pushed into the pending review
   * with `addPullRequestReviewThreadReply` instead of starting a new thread.
   */
  inReplyTo?: string;
}

/** The reader, or the review chat writing through `reviewer-state comment`. */
/**
 * The reader, or an agent in the review chat (and the harness it ran on).
 * The server reads comments stored as "claude" as `{ agent: "claude-code" }`.
 */
export type CommentActor = "you" | { agent: string };

/** A deleted draft, still restorable for a while (the server's trash). */
export type DeletedComment = DraftComment & { deletedAt: string; deletedBy: CommentActor };

/** The one predicate the whole UI branches on. Tolerant of older payloads. */
export function isFileComment(c: {
  subjectType?: CommentSubject;
  line?: number | null;
}): boolean {
  return c.subjectType === "file" || c.line === null || c.line === undefined;
}

