export type Kind =
  | "core-logic"
  | "connective-tissue"
  | "wiring"
  | "ripple"
  | "tests"
  | "docs";

export type Attention = "must-read" | "skim" | "skip";

export type RiskFlag =
  | "auth"
  | "migration"
  | "concurrency"
  | "money"
  | "external-call"
  | "security";

export const KINDS: Kind[] = [
  "core-logic",
  "connective-tissue",
  "wiring",
  "ripple",
  "tests",
  "docs",
];

export const ATTENTIONS: Attention[] = ["must-read", "skim", "skip"];

/** A hunk as listed in revisions/<n>/files.json. */
export interface Hunk {
  id: string;
  file: string;
  oldStart: number;
  oldLines: number;
  newStart: number;
  newLines: number;
  header: string;
  /**
   * Raw patch body for the hunk (the lines after the @@ header, each still
   * carrying its leading ' ', '+' or '-'). Derived by `client.ts` from the
   * `text` field core writes into files.json; only absent for hunks that
   * predate that field, in which case we recover it from the raw diff text.
   */
  lines?: string[];
  /** Content lines only, as core computed hunk identity from. */
  addedLines?: string[];
  removedLines?: string[];
}

export interface FileEntry {
  path: string;
  oldPath?: string;
  status?: "added" | "modified" | "removed" | "renamed";
  additions?: number;
  deletions?: number;
  binary?: boolean;
  /**
   * Set when Purview classified the file as generated or a lockfile (see
   * {@link FileGenerated}). Every hunk of such a file sits in the fixed
   * `generated` unit and the analysis never reads it.
   */
  generated?: FileGenerated;
  hunks: Hunk[];
}

/**
 * Which signal marked a file as generated, first match wins in this order:
 * the repo's own patterns, the PR head's `.gitattributes`
 * (`linguist-generated` / `linguist-vendored`), a known lockfile name, a
 * generated-path convention (`*.pb.go`, `__generated__/`…), or a "Code
 * generated … DO NOT EDIT" marker near the top of the file.
 */
export type GeneratedSource = "repo" | "gitattributes" | "lockfile" | "path" | "marker";

export interface FileGenerated {
  source: GeneratedSource;
  /** the matching pattern, or the marker line ("Code generated by protoc-gen-go") */
  detail?: string;
}

export interface FilesJson {
  files: FileEntry[];
}

export type FindingSeverity = "warning" | "note";

/**
 * A claim the analysis verified in the local checkout: `warning` = something
 * is likely wrong, `note` = a verified-OK answer to a question the reviewer
 * would otherwise have had to chase. `evidence` is the location(s) read.
 * Purely an annotation — nothing in the app acts on it.
 */
export interface Finding {
  severity: FindingSeverity;
  text: string;
  evidence: string;
}

/** One line about what a revision changed in a unit (see `ReviewUnit.changelog`). */
export interface UnitChangelogEntry {
  revision: number;
  text: string;
}

export interface ReviewUnit {
  id: string;
  title: string;
  summary: string;
  kind: Kind;
  attention: Attention;
  attentionWhy: string;
  riskFlags: RiskFlag[];
  hunkIds: string[];
  order: number;
  /** absent on units that verified nothing, and on any state predating findings */
  findings?: Finding[];
  /**
   * What each later revision changed in this unit, oldest first, one entry per
   * revision. Absent until an incremental analysis writes one; a full
   * re-analysis starts it fresh.
   */
  changelog?: UnitChangelogEntry[];
  /**
   * Set only on a "husk": a unit every hunk of which left the PR in this
   * revision. Husks never appear in `PrState.units` — the client adapter
   * moves them to `PrState.removedUnits` — and they vanish on the next revision.
   */
  removedAtRevision?: number;
  /** On a husk: the reader had viewed every hunk of it before they left. */
  readBeforeRemoval?: boolean;
  /**
   * Set only by Purview itself, never by the analysis: `"generated"` marks
   * the one fixed unit (id {@link GENERATED_UNIT_ID}) holding every hunk of
   * every generated file and lockfile. It is rebuilt on each revision, always
   * `skip`, and is not review work — nothing that counts progress, readiness
   * or "has this PR been analyzed" should count it.
   */
  origin?: "generated";
}

/** The id of the fixed generated-files unit (see `ReviewUnit.origin`). */
export const GENERATED_UNIT_ID = "generated";

/** The fixed unit Purview builds out of generated files and lockfiles. */
export function isGeneratedUnit(u: Pick<ReviewUnit, "origin">): boolean {
  return u.origin === "generated";
}

/** A unit whose hunks all left the PR (see `ReviewUnit.removedAtRevision`). */
export function isRemovedUnit(u: Pick<ReviewUnit, "removedAtRevision">): boolean {
  return u.removedAtRevision !== undefined;
}

/**
 * Word-level diff-of-diffs, as computed by core and served by
 * `GET /api/prs/:key/hunks/:id/diff-of-diffs`. It is line-oriented: each line
 * is unchanged/added/removed, or `modified` with a word-level breakdown.
 */
export interface WordPart {
  value: string;
  type: "same" | "added" | "removed";
}

export interface DiffOfDiffsLine {
  type: "unchanged" | "added" | "removed" | "modified";
  oldLine?: string;
  newLine?: string;
  /** word-level breakdown, only for `modified` lines */
  parts?: WordPart[];
}

export interface DiffOfDiffs {
  lines: DiffOfDiffsLine[];
  changed: boolean;
}

/**
 * The lines one revision changed, mapped onto the current revision's hunks —
 * `GET /api/prs/:key/revisions/:n/line-changes` (core's RevisionLineChanges).
 */
export interface HunkLineChange {
  currentHunkId: string;
  originHunkId: string;
  file: string;
  status: "fuzzy" | "renamed" | "new";
  /**
   * Sorted indexes into the current hunk's body lines (`hunk.lines`, the
   * `buildRows` index space) of the lines the revision introduced.
   */
  lines: number[];
  /** lines the revision deleted outright (an edit's old side is not counted) */
  removedCount: number;
  /**
   * Where those deletions sit now: `line` is the body index of the line right
   * after the deleted run (the body's length when it was at the very end).
   */
  removedAt: { line: number; count: number }[];
  /** how many of the revision's lines later revisions rewrote or removed */
  rewrittenSince: number;
  /** `rewrittenSince` by the revision that did it, sorted; absent when 0 (or from an older server) */
  rewrittenBy?: { revision: number; count: number }[];
  /** no later revision touched the hunk */
  exactAtCurrent: boolean;
  /** a later step couldn't be followed; positions assumed carried over */
  uncertain?: boolean;
  truncated?: boolean;
}

export interface GoneLineChangeHunk {
  originHunkId: string;
  lastHunkId: string;
  file: string;
  goneAtRevision: number;
  unitId?: string;
}

export interface RevisionLineChanges {
  revision: number;
  currentRevision: number;
  hunks: HunkLineChange[];
  goneCount: number;
  gone: GoneLineChangeHunk[];
}

