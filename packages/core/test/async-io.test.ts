import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { afterEach, expect, it } from "vitest";
import { gatherGeneratedFactsAsync } from "../src/generated-io.js";
import { fetchFileHeadsAsync, setGhAsyncRunner, setGhRunner } from "../src/github.js";
import { parseDiff } from "../src/parse-diff.js";
import { prCheckoutPath, type PrKey } from "../src/paths.js";

const key: PrKey = { host: "github.com", owner: "acme", repo: "widgets", number: 7 };
let root: string;
afterEach(() => {
  setGhRunner(null);
  setGhAsyncRunner(null);
  if (root) fs.rmSync(root, { recursive: true, force: true });
});

it("reads generated markers and attributes through asynchronous local cat-file", async () => {
  root = fs.mkdtempSync(path.join(os.tmpdir(), "purview-async-generated-"));
  const repo = prCheckoutPath(key, root);
  fs.mkdirSync(repo, { recursive: true });
  const git = (...args: string[]) => execFileSync("git", ["-C", repo, ...args], { encoding: "utf8" }).trim();
  git("init", "-q");
  fs.writeFileSync(path.join(repo, ".gitattributes"), "schema/* linguist-generated\n");
  fs.writeFileSync(path.join(repo, "client.ts"), "// Code generated by example. DO NOT EDIT.\nexport {};\n");
  git("add", ".");
  git("-c", "user.name=Test", "-c", "user.email=test@example.com", "-c", "commit.gpgsign=false", "commit", "-qm", "fixture");
  const sha = git("rev-parse", "HEAD");
  const files = parseDiff("diff --git a/client.ts b/client.ts\n--- a/client.ts\n+++ b/client.ts\n@@ -10 +10 @@\n-old\n+new\n");
  let networkCalls = 0;
  setGhAsyncRunner(async () => { networkCalls++; throw new Error("local objects should suffice"); });
  const facts = await gatherGeneratedFactsAsync(key, files, sha, root);
  expect(facts.partial).toBe(false);
  expect(facts.gitattributes).toBe("schema/* linguist-generated\n");
  expect(facts.markers["client.ts"]).toContain("Code generated");
  expect(networkCalls).toBe(0);
});

it("awaits both blob passes and excludes oversized or binary heads", async () => {
  let calls = 0;
  let syncCalls = 0;
  setGhRunner(() => { syncCalls++; throw new Error("sync gh"); });
  setGhAsyncRunner(async args => {
    calls++;
    const query = args.find(a => a.startsWith("query="))!;
    return JSON.stringify({ data: { repository: query.includes("byteSize")
      ? { f0: { byteSize: 30, isBinary: false }, f1: { byteSize: 999999, isBinary: false }, f2: { byteSize: 3, isBinary: true } }
      : { f0: { text: "first\nsecond\nthird" } } } });
  });
  const result = await fetchFileHeadsAsync(key, "head", ["small.ts", "big.ts", "binary"], 2);
  expect(result).toEqual({ ok: true, heads: new Map([["small.ts", ["first", "second"]]]) });
  expect(calls).toBe(2);
  expect(syncCalls).toBe(0);
});
